import { useEffect, useRef, useState } from "react";
import QRCode from "qrcode";
import { useFullscreen } from "../lib/useFullscreen";

/** The link a session's QR code points at: the submit form with the session
 * picked and the code filled in, so players only type their result. */
export function submitLinkFor(sessionId: string, code: string): string {
  return `${window.location.origin}/submit?session=${encodeURIComponent(sessionId)}&code=${encodeURIComponent(code)}`;
}

/** Full-screen QR for a cash night: put it on a laptop facing the room (or
 * pass a phone round) and players scan to submit. Generated locally — the
 * link never goes to a third-party QR service. */
export function SessionQrOverlay({
  sessionId,
  code,
  title,
  onClose,
}: {
  sessionId: string;
  code: string;
  title: string;
  onClose: () => void;
}) {
  const ref = useRef<HTMLDivElement>(null);
  const { isFullscreen, toggle } = useFullscreen(ref);
  const [svg, setSvg] = useState<string | null>(null);
  const link = submitLinkFor(sessionId, code);

  useEffect(() => {
    let live = true;
    // Dark-on-white with a quiet zone scans far more reliably than a
    // themed QR, so this is the one deliberately light element.
    void QRCode.toString(link, {
      type: "svg",
      errorCorrectionLevel: "M",
      margin: 2,
      color: { dark: "#0A0B0D", light: "#FFFFFF" },
    }).then((s) => live && setSvg(s));
    return () => {
      live = false;
    };
  }, [link]);

  useEffect(() => {
    const onKey = (e: KeyboardEvent) => e.key === "Escape" && !document.fullscreenElement && onClose();
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  }, [onClose]);

  return (
    <div
      ref={ref}
      role="dialog"
      aria-modal="true"
      aria-label={`Submission QR code for ${title}`}
      className="fixed inset-0 z-50 flex flex-col items-center justify-center gap-4 overflow-y-auto bg-bg-0 p-4"
    >
      <p className="font-display text-sm uppercase tracking-[0.3em] text-muted">{title}</p>
      <h2 className="text-center font-display text-2xl font-semibold tracking-[0.12em] sm:text-4xl">
        SCAN TO SUBMIT YOUR RESULT
      </h2>
      <div
        className="aspect-square w-[min(80vw,60vh)] rounded-lg bg-white [&>svg]:h-full [&>svg]:w-full"
        // Generated by the qrcode library from our own URL — no user HTML.
        dangerouslySetInnerHTML={svg ? { __html: svg } : undefined}
      />
      <p className="text-center text-muted">
        Or go to <span className="font-mono text-text">{window.location.host}/submit</span> and enter
      </p>
      <div className="tnum font-mono text-4xl font-bold tracking-[0.3em] text-ember sm:text-5xl">
        {code}
      </div>
      <div className="flex gap-2">
        <button
          className="rounded border border-steel px-3 py-1.5 text-sm hover:border-ember hover:text-ember"
          onClick={toggle}
        >
          {isFullscreen ? "Exit full screen" : "Full screen"}
        </button>
        <button
          className="rounded border border-steel px-3 py-1.5 text-sm hover:border-ember hover:text-ember"
          onClick={() => void navigator.clipboard?.writeText(link)}
        >
          Copy link
        </button>
        <button
          className="rounded bg-ember-deep px-3 py-1.5 font-display text-sm text-white hover:bg-ember"
          onClick={onClose}
        >
          Close
        </button>
      </div>
    </div>
  );
}
